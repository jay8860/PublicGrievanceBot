"""Archived photo storage on a persistent disk (Railway volume).

Telegram ``file_id`` values are not permanent: they break when the bot token is
rotated and Telegram keeps its own retention window. So every before/after
photo the platform receives is also copied under ``MEDIA_ROOT``.

Set ``MEDIA_ROOT`` to a folder on the mounted volume, e.g. ``/data/media``.
When it is unset the platform keeps the old behaviour (Telegram file_id only)
and nothing here ever raises: a storage failure must never lose a complaint.
"""

import hashlib
import logging
import os
from datetime import datetime
from typing import Optional

from config import get_env

logger = logging.getLogger(__name__)


def media_root() -> str:
    """Configured photo folder ('' when archiving is disabled)."""
    return (get_env("MEDIA_ROOT", "") or "").rstrip("/\\")


def enabled() -> bool:
    return bool(media_root())


def _safe_ticket(ticket_ref: str) -> str:
    """Ticket refs are generated by us, but never trust one in a file name."""
    cleaned = "".join(char for char in (ticket_ref or "") if char.isalnum() or char in "-_")
    return cleaned or "unknown"


def save_photo(data, ticket_ref: str, kind: str = "original") -> str:
    """Write photo bytes under ``MEDIA_ROOT/photos/<year>/``; return the key.

    The key is relative to ``MEDIA_ROOT`` so the volume can be moved or mounted
    at a different path later without rewriting the database. Returns "" when
    archiving is disabled or the write failed.
    """
    root = media_root()
    if not root or not data:
        return ""

    year = str(datetime.utcnow().year)
    digest = hashlib.sha256(data).hexdigest()[:12]
    key = f"photos/{year}/{_safe_ticket(ticket_ref)}-{_safe_ticket(kind)}-{digest}.jpg"
    path = os.path.join(root, key)

    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as handle:
            handle.write(data)
    except OSError as exc:                # read-only volume, bad mount, full disk
        logger.warning("Could not archive %s photo for %s: %s", kind, ticket_ref, exc)
        return ""
    return key


def photo_path(key: str) -> Optional[str]:
    """Absolute path for a stored key, or ``None`` if missing/outside the root."""
    root = media_root()
    if not root or not key:
        return None

    root_abs = os.path.abspath(root)
    path = os.path.abspath(os.path.join(root_abs, key))
    if path != root_abs and not path.startswith(root_abs + os.sep):
        logger.warning("Rejected image key outside MEDIA_ROOT: %s", key)
        return None
    return path if os.path.isfile(path) else None


def usage_bytes() -> int:
    """Total bytes used by archived photos (for the settings page)."""
    root = media_root()
    if not root or not os.path.isdir(root):
        return 0
    total = 0
    for folder, _dirs, files in os.walk(os.path.join(root, "photos")):
        for name in files:
            try:
                total += os.path.getsize(os.path.join(folder, name))
            except OSError:
                continue
    return total
